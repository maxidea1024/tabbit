def rows():
    """`StringTable` 에 들어갈 줄들."""
    out = []
    for kind, entries in (('trigger', TRIGGER), ('cond', CONDITION), ('op', OPERATION),
                          ('unit', UNIT), ('rule', RULE)):
        for ident, ko, en in entries:
            out.append(['phrase.%s.%s' % (kind, ident), ko, en])
    for ident, ko, en in ENUM:
        out.append(['phrase.%s' % ident, ko, en])
    return out
