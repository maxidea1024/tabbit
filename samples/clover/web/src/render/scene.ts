// 씬.
//
// **이 게임에는 씬이 넷이고 순서가 있습니다** — 데이터를 읽고(`loading`), 계정을
// 정하고(`login`), 시작을 기다리고(`title`), 판이 돕니다(`run`).
//
// `loading` 은 화면을 그리는 것이 준비되기 전이므로 진입점이 DOM 한 줄로 가지고 있고,
// 나머지 셋은 `Game` 안에 있습니다 — 그래서 판을 접고 타이틀로 가는 데 페이지를 다시 읽을
// 일이 없습니다. **다시 읽으면 로딩이 한 번 더 보이는데, 판을 접는 것과 데이터를 읽는 것은
// 아무 관계가 없습니다.**
//
// **`login` 은 판이 아니라 씬입니다.** 계정을 정하는 것은 게임 위에 잠깐 뜨는 일이 아니라
// 게임에 들어가기 전에 지나는 자리입니다 — 판으로 두면 뒤에 타이틀이 비쳐 이미 시작한
// 것처럼 보입니다.
//
// **한 번만 지납니다.** 로그인했거나 싱글플레이로 정했으면 `loading` 에서 곧바로
// `title` 입니다. 타이틀의 계정 단추가 다시 이 씬으로 보냅니다.

export type Scene = 'loading' | 'login' | 'title' | 'run'
