namespace Tabbit;

/// <summary>
/// The banner every emitted file carries in its header, and the rule for finding it again.
/// </summary>
/// <remarks>
/// This is load-bearing, not decoration. The sweep deletes a file from an output directory
/// only when the file says this about itself, which is what makes it safe to point a target
/// at a directory a person also keeps things in: renaming a table removes its old file, and
/// somebody's own source sitting next to it is left alone.
///
/// One sentence, every target. It used to be six spellings - the phrase shouted inside an
/// `auto-generated` block, the Go toolchain's own wording, a hyphen instead of a full stop
/// in markup, and a runtime header that said it twice in one line. None of that was visible
/// from the sweep, which matches a substring and so accepted them all; what it cost was a
/// reader having to check, at each of two dozen sites, whether the words in front of them
/// were the ones that count.
///
/// The Scriban templates still spell it themselves: a template is text, and reaching a
/// constant from one would mean pushing it into every view. What keeps those honest is
/// <c>GeneratedFileMarkerTests</c>, which reads every emitted file of a converted fixture
/// and asks whether the sweep would recognise it.
/// </remarks>
public static class GeneratedFileMarker
{
    /// <summary>
    /// The phrase itself, as written into a header.
    /// </summary>
    public const string Text = "Generated by Tabbit";

    /// <summary>
    /// The banner line: the phrase and the warning that follows it.
    /// </summary>
    public const string Banner = Text + ". DO NOT EDIT.";

    /// <summary>
    /// How far into a file to look for it.
    /// </summary>
    /// <remarks>
    /// Only the head is examined. Every target writes the marker as a header, and a file
    /// that merely mentions the phrase somewhere in the middle is somebody's own source -
    /// which is the one thing the sweep must never delete.
    /// </remarks>
    public const int Window = 1024;

    /// <summary>
    /// Whether text taken from the head of a file claims this tool wrote it.
    /// </summary>
    /// <remarks>
    /// Case-insensitive, which costs nothing now that every target writes the phrase the
    /// same way, and still recognises output written before they did.
    /// </remarks>
    public static bool IsMarked(string head)
    {
        return head is not null
            && head.IndexOf(Text, System.StringComparison.OrdinalIgnoreCase) >= 0;
    }

    /// <summary>
    /// Whether a file's contents already carry the marker in the window the sweep reads.
    /// </summary>
    public static bool HeadIsMarked(string contents)
    {
        if (contents is null)
            return false;

        return IsMarked(contents.Substring(0, System.Math.Min(Window, contents.Length)));
    }
}
