using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Xunit;

namespace Tabbit.Tests;

/// <summary>
/// Every file a conversion writes has to say, in its own header, that this tool wrote it.
/// </summary>
/// <remarks>
/// The marker is what gives the sweep permission to delete a file, so a target that stops
/// writing one leaves it in the consumer's project forever. That failure is invisible at the
/// point it is caused: nothing goes wrong during the run that lost the header, and the stale
/// file turns up months later when somebody renames a table.
///
/// It has happened twice. The runtime files were copied out of `lib/` verbatim and so arrived
/// without a header; the HTML pages never had one at all, which came out only when a naming
/// fix renamed twenty of them at once and the old twenty stayed. Both were found by reading
/// output, not by a gate. This is the gate.
///
/// It reads what a conversion actually produced rather than the templates, because the
/// templates are text and spell the phrase themselves - which is the thing that can drift.
/// </remarks>
public class GeneratedFileMarkerTests
{
    /// <summary>
    /// Written by a conversion but not by a generator: data, not source, and the sweep is
    /// not asked to manage them.
    /// </summary>
    private static readonly string[] NotSourceExtensions =
    [
        ".tcb", ".json", ".bin", ".png", ".lock",
    ];

    [Fact]
    public void Every_emitted_source_file_says_that_Tabbit_wrote_it()
    {
        var result = TabbitRunner.Convert("core");
        Assert.True(result.Succeeded, $"Conversion failed.{Environment.NewLine}{result.Describe()}");

        var unmarked = new List<string>();

        foreach (string path in Directory.EnumerateFiles(
                     RepoLayout.OutputDir("core"), "*", SearchOption.AllDirectories))
        {
            if (NotSourceExtensions.Contains(Path.GetExtension(path), StringComparer.OrdinalIgnoreCase))
                continue;

            if (!Marked(path))
                unmarked.Add(path);
        }

        Assert.True(unmarked.Count == 0,
            "These files carry no `Generated by Tabbit` header, so the sweep can never " +
            "remove them - a rename would leave the old name behind for good:" +
            Environment.NewLine +
            string.Join(Environment.NewLine, unmarked.Select(p => "  " + p)));
    }

    /// <summary>
    /// Asked exactly the way <see cref="Helpers.StagingFiles"/> asks it: the same window, and
    /// the same comparison. A test that read the whole file would pass on output the sweep
    /// would still walk past.
    /// </summary>
    private static bool Marked(string path)
    {
        using var stream = File.OpenRead(path);

        var head = new byte[GeneratedFileMarker.Window];
        int read = stream.Read(head, 0, head.Length);

        return read > 0
            && GeneratedFileMarker.IsMarked(System.Text.Encoding.UTF8.GetString(head, 0, read));
    }
}
